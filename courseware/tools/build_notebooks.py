def write_notebook(builder) -> pathlib.Path:
    """Build one notebook and write it under OUT. The cell counter restarts for
    each notebook, so regenerating is byte-identical (the sync test depends on
    it). Call it with one builder to regenerate that notebook alone."""
    global _COUNTER
    OUT.mkdir(parents=True, exist_ok=True)
    _COUNTER = itertools.count()
    nb, name = builder()
    path = OUT / name
    path.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n")
    n_code = sum(1 for c in nb["cells"] if c["cell_type"] == "code")
    n_md = sum(1 for c in nb["cells"] if c["cell_type"] == "markdown")
    print(f"  wrote {path.relative_to(REPO)}  ({n_md} md + {n_code} code cells)")
    print(f"        {colab_url(name)}")
    return path


